#!/usr/bin/env python3
"""Keep copied recipes identical to their compiled previews, including helpers/imports."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'app/shared/src/commonMain/kotlin/com/toutiaoyan/compose/ui/catalog/docs'
source = (DOCS / 'ToastRecipes.kt').read_text()
header = source.split('// region shared', 1)[0]
header = re.sub(r'^package .*\n', '', header, flags=re.M).strip()

def region(name):
    return source.split('// region ' + name + '\n', 1)[1].split('// endregion ' + name, 1)[0].strip()

output = ['// Generated by scripts/generate_toast_recipe_code.py; edit ToastRecipes.kt.',
          'package com.toutiaoyan.compose.ui.catalog.docs', '']
recipes = {
    'Installation': ['installation'],
    'Usage': ['shared', 'usage'],
    'Action': ['action'],
    'Default': ['shared', 'action', 'default'],
    'Types': ['types'],
    'Promise': ['promise'],
    'Duration': ['duration'],
    'Position': ['position'],
    'CloseButton': ['closeButton'],
}
for name, regions in recipes.items():
    code = '\n\n'.join([header, *(region(part) for part in regions)])
    # A Kotlin raw string must preserve interpolation for the user's copied code.
    code = code.replace('$', "${'$'}")
    output += ['internal val toast' + name + 'RecipeCode =', '    """',
               *['    ' + line if line else '' for line in code.splitlines()],
               '    """.trimIndent()', '']
target = DOCS / 'ToastRecipeCode.kt'
generated = '\n'.join(output)
if not target.exists() or target.read_text() != generated:
    target.write_text(generated)
print(f'Generated {len(recipes)} standalone Toast snippets from compiled source')
