#!/usr/bin/env python3
"""Generate standalone Toggle snippets from the Kotlin used by the catalog previews."""

from pathlib import Path
import re
import sys
from textwrap import dedent

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "app/shared/src/commonMain/kotlin/com/toutiaoyan/compose/ui/catalog/docs"
SOURCE = (DOCS / "ToggleOfficialRecipes.kt").read_text(encoding="utf-8")
HEADER = SOURCE.split("// region usage\n", 1)[0]
OPT_IN = next(line for line in HEADER.splitlines() if line.startswith("@file:"))
IMPORTS = [line for line in HEADER.splitlines() if line.startswith("import ")]
RECIPES = [
    "default", "outline", "text", "size", "disabled", "rtl", "defaultVariant",
    "defaultSize", "defaultDisabled", "uncontrolled", "defaultPressed",
    "accessibleLabel", "defaultLabel", "invalid",
]


def region(name):
    return SOURCE.split(f"// region {name}\n", 1)[1].split(f"// endregion {name}", 1)[0].strip()


def recipe_code(name):
    body = region(name).replace("internal fun ", "fun ")
    if name in ("default", "rtl"):
        body += "\n\n" + region("bookmark")
    imports = []
    for line in IMPORTS:
        symbol = line.rsplit(".", 1)[1]
        used = " by remember " in body if symbol in ("getValue", "setValue") else re.search(rf"\b{symbol}\b", body)
        if used:
            imports.append(line)
    return "\n\n".join([OPT_IN, "\n".join(imports), body]).replace("$", "${'$'}")


def main():
    use_import = next(line for line in IMPORTS if line.endswith(".Toggle"))
    use_call = dedent(region("usage").split("{\n", 1)[1].rsplit("}", 1)[0]).strip()
    output = [
        "// Generated by scripts/generate_toggle_recipe_code.py. Edit ToggleOfficialRecipes.kt.",
        "package com.toutiaoyan.compose.ui.catalog.docs",
        "",
        f'internal const val toggleUsageImportCode = "{use_import}"',
        f'internal const val toggleUsageRecipeCode = """{use_call}"""',
        "",
    ]
    for name in RECIPES:
        property_name = f"toggle{name[0].upper()}{name[1:]}RecipeCode"
        output += [
            f"internal val {property_name} =",
            '    """',
            *["    " + line if line else "" for line in recipe_code(name).splitlines()],
            '    """.trimIndent()',
            "",
        ]

    target = DOCS / "ToggleRecipeCode.kt"
    generated = "\n".join(output)
    if target.exists() and target.read_text(encoding="utf-8") == generated:
        return
    if "--check" in sys.argv:
        sys.exit("Toggle recipes are stale. Run scripts/generate_toggle_recipe_code.py")
    target.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
