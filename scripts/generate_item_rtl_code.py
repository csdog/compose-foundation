#!/usr/bin/env python3
"""Export the compiled Item RTL recipe with public font resources."""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'app/shared/src/commonMain/kotlin/com/toutiaoyan/compose/ui/catalog/docs'
code = (DOCS / 'ItemRtlRecipe.kt').read_text()
code = re.sub(r'^package .*\n', '', code, flags=re.M).strip()
code = '\n'.join(line for line in code.splitlines() if 'ui.catalog.catalog' not in line and 'import androidx.compose.ui.platform.testTag' not in line)
code = code.replace('internal fun ', 'fun ')
code = code.replace(
    'import androidx.compose.ui.unit.*',
    'import androidx.compose.ui.unit.*\n'
    'import androidx.compose.ui.text.font.FontFamily\n'
    'import androidx.compose.ui.text.font.FontWeight\n'
    'import compose_foundation.app.shared.generated.resources.*\n'
    'import org.jetbrains.compose.resources.Font',
)
code = code.replace('catalogArabicFontFamily()', 'FontFamily(Font(Res.font.catalog_arabic_regular, FontWeight.Normal),\n        Font(Res.font.catalog_arabic_medium, FontWeight.Medium))')
code = code.replace('catalogHebrewFontFamily()', 'FontFamily(Font(Res.font.catalog_hebrew_regular, FontWeight.Normal),\n        Font(Res.font.catalog_hebrew_medium, FontWeight.Medium))')
code = re.sub(r'\.testTag\("[^\"]*"\)', '', code)
code = code.replace('$', "${'$'}")
output = ['// Generated by scripts/generate_item_rtl_code.py; edit ItemRtlRecipe.kt.', 'package com.toutiaoyan.compose.ui.catalog.docs', '', 'internal val itemRtlRecipeCode =', '    """', *['    ' + line if line else '' for line in code.splitlines()], '    """.trimIndent()', '']
(DOCS / 'ItemRtlRecipeCode.kt').write_text('\n'.join(output))
