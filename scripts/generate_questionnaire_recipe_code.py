#!/usr/bin/env python3
"""Keep official Questionnaire snippets backed by their compiled previews."""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'app/shared/src/commonMain/kotlin/com/toutiaoyan/compose/ui/catalog/docs'
default_source = (DOCS / 'QuestionnaireRecipes.kt').read_text()
catalog_source = (DOCS / 'QuestionnaireDoc.kt').read_text()

EXAMPLES = {
    'MultipleSelection': 'MultipleSelectionPreview',
    'FreeformAnswer': 'FreeformAnswerPreview',
    'ExplicitSkip': 'ExplicitSkipPreview',
    'Shortcuts': 'ShortcutsPreview',
    'CustomValidation': 'CustomValidationPreview',
    'Controlled': 'ControlledPreview',
    'Resume': 'ResumePreview',
    'ConditionalItems': 'ConditionalItemsPreview',
    'NavigationState': 'NavigationStatePreview',
    'CustomProgress': 'CustomProgressPreview',
    'AnimatedItems': 'AnimatedItemsPreview',
    'Card': 'CardPreview',
    'Dialog': 'DialogPreview',
}

DECLARATION = re.compile(
    r'^(?:@Composable\n)?(?:private|internal) '
    r'(?:fun [^\n]*?\b(?P<function>\w+)\s*\(|(?:val|class) (?P<member>\w+)\b)',
    re.MULTILINE,
)


def region(name):
    return default_source.split(f'// region {name}\n', 1)[1].split(f'// endregion {name}', 1)[0].strip()


def declarations(source):
    starts = list(DECLARATION.finditer(source))
    ends = [match.start() for match in starts[1:]] + [len(source)]
    return {
        match['function'] or match['member']: source[match.start():end].strip()
        for match, end in zip(starts, ends)
    }


def dependencies(entry, definitions):
    selected = {entry}
    pending = [entry]
    while pending:
        body = definitions[pending.pop()]
        for name in definitions.keys() - selected:
            declaration = definitions[name]
            token = re.escape(name)
            if re.search(r'^(?:private|internal) (?:fun|class) ', declaration, re.MULTILINE):
                reference = rf'\b{token}\s*\(|::\s*{token}\b'
            else:
                reference = rf'\b{token}\b'
            if re.search(reference, body):
                selected.add(name)
                pending.append(name)
    return [definitions[name] for name in definitions if name in selected]


def snippet(entry, definitions, imports):
    body = '\n\n'.join(dependencies(entry, definitions))
    body = body.replace(f'private fun {entry}(', f'fun {entry}(', 1)
    used = [
        line for line in imports
        if line.endswith('.*') or re.search(rf'\b{re.escape(line.rsplit(".", 1)[1])}\b', body)
    ]
    return '\n\n'.join([
        '@file:OptIn(androidx.compose.foundation.style.ExperimentalFoundationStyleApi::class)',
        '\n'.join(used),
        body,
    ])


def emit(name, code):
    assert '"""' not in code, name
    code = code.replace('$', "${'$'}")
    return [
        f'internal val questionnaire{name}RecipeCode =',
        '    """',
        *['    ' + line if line else '' for line in code.splitlines()],
        '    """.trimIndent()',
        '',
    ]


def main():
    default_header = default_source.split('// region shared', 1)[0]
    default_header = re.sub(r'^package .*\n', '', default_header, flags=re.MULTILINE).strip()
    helpers = {
        **declarations(region('shared')),
        **declarations(catalog_source.split('\nval questionnaireDoc =', 1)[0]),
    }
    imports = sorted(set(
        re.findall(r'^import [^\n]+', default_header + '\n' + catalog_source.split('@Composable', 1)[0],
                   re.MULTILINE)
    ))
    output = [
        '// Generated by scripts/generate_questionnaire_recipe_code.py from the compiled previews.',
        'package com.toutiaoyan.compose.ui.catalog.docs',
        '',
    ]
    output += emit('Default', '\n\n'.join([default_header, region('shared'), region('default')]))
    for name, entry in EXAMPLES.items():
        output += emit(name, snippet(entry, helpers, imports))
    target = DOCS / 'QuestionnaireRecipeCode.kt'
    generated = '\n'.join(output)
    if not target.exists() or target.read_text() != generated:
        target.write_text(generated)
    print(f'Generated {1 + len(EXAMPLES)} standalone recipe snippets')


if __name__ == '__main__':
    main()
