#!/usr/bin/env python3
"""Keep copied recipes identical to their compiled previews, including helpers/imports."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'app/shared/src/commonMain/kotlin/com/toutiaoyan/compose/ui/catalog/docs'
source = (DOCS / 'ProgressRecipes.kt').read_text()
header = source.split('// region shared', 1)[0]
header = re.sub(r'^package .*\n', '', header, flags=re.M).strip()
header = '\n'.join(line for line in header.splitlines() if 'ui.catalog.catalog' not in line and 'import androidx.compose.ui.platform.testTag' not in line)
header += '\nimport androidx.compose.ui.text.font.FontFamily\nimport androidx.compose.ui.text.font.FontWeight\nimport compose_foundation.app.shared.generated.resources.*\nimport org.jetbrains.compose.resources.Font'

def region(name):
    return source.split('// region ' + name + '\n', 1)[1].split('// endregion ' + name, 1)[0].strip()

output = ['// Generated by scripts/generate_progress_recipe_code.py; edit ProgressRecipes.kt.',
          'package com.toutiaoyan.compose.ui.catalog.docs', '']
for name in ['default', 'label', 'controlled', 'rtl']:
    code = '\n\n'.join([header, region('shared'), region(name)])
    code = code.replace('internal fun ', 'fun ')
    code = code.replace('catalogArabicFontFamily()', 'FontFamily(Font(Res.font.catalog_arabic_regular, FontWeight.Normal),\n        Font(Res.font.catalog_arabic_medium, FontWeight.Medium))')
    code = code.replace('catalogHebrewFontFamily()', 'FontFamily(Font(Res.font.catalog_hebrew_regular, FontWeight.Normal),\n        Font(Res.font.catalog_hebrew_medium, FontWeight.Medium))')
    code = re.sub(r'\.testTag\("[^"]*"\)', '', code)
    code += '\n\nProgress' + name.title() + 'Recipe()'
    # A Kotlin raw string must preserve interpolation for the user's copied code.
    code = code.replace('$', "${'$'}")
    output += ['internal val progress' + name.title() + 'RecipeCode =', '    """',
               *['    ' + line if line else '' for line in code.splitlines()],
               '    """.trimIndent()', '']
target = DOCS / 'ProgressRecipeCode.kt'
generated = '\n'.join(output)
if not target.exists() or target.read_text() != generated:
    target.write_text(generated)
print('Generated four standalone recipe snippets from compiled preview source')
