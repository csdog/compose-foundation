#!/usr/bin/env python3
"""Generate the public Marker action recipe from the compiled preview."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'app/shared/src/commonMain/kotlin/com/toutiaoyan/compose/ui/catalog/docs'
source = (DOCS / 'MarkerActionRecipes.kt').read_text()
code = '\n'.join(
    line for line in source.splitlines()
    if not line.startswith('package ')
    and 'import com.toutiaoyan.compose.ui.catalog.' not in line
    and 'import androidx.compose.ui.platform.testTag' not in line
)
code = code.replace('    val navigation = LocalDocNavigation.current\n', '')
code = code.replace('navigation?.navigate("links-and-buttons") ?: ', '')
code = code.replace('internal fun ', 'fun ')
code = re.sub(r'\.testTag\("[^\"]*"\)', '', code)
code = code.replace('$', "${'$'}") + '\n\nMarkerActionsRecipe()'
generated = (
    '// Generated by scripts/generate_marker_action_code.py.\n'
    'package com.toutiaoyan.compose.ui.catalog.docs\n\n'
    'internal val markerActionCode =\n    """\n'
    + '\n'.join('    ' + line if line else '' for line in code.splitlines())
    + '\n    """.trimIndent()\n'
)
(DOCS / 'MarkerActionCode.kt').write_text(generated)
