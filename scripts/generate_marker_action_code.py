#!/usr/bin/env python3
"""Generate the public Marker action recipe from the compiled preview."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'app/shared/src/commonMain/kotlin/com/toutiaoyan/compose/ui/catalog/docs'
source = (DOCS / 'MarkerActionRecipes.kt').read_text()
code = '\n'.join(
    line for line in source.splitlines()
    if not line.startswith('package ')
    and 'import com.toutiaoyan.compose.ui.catalog.' not in line
    and line != 'import androidx.compose.ui.platform.LocalUriHandler'
    and 'import androidx.compose.ui.platform.testTag' not in line
)
replacements = (
    (
        '@Composable\ninternal fun MarkerActionsRecipe() {',
        '/** Navigate to `#links-and-buttons` in the current page from [onOpenLink]. */\n'
        '@Composable\nfun MarkerActionsRecipe(onOpenLink: () -> Unit) {',
    ),
    ('    val navigation = LocalDocNavigation.current\n', ''),
    ('    val uri = LocalUriHandler.current\n', ''),
    (
        'MarkerLinkAction { navigation?.navigate("links-and-buttons") ?: uri.openUri("#links-and-buttons") }',
        'MarkerLinkAction(onOpenLink)',
    ),
)
for old, new in replacements:
    if code.count(old) != 1:
        raise ValueError(f'Expected one Marker preview export match: {old!r}')
    code = code.replace(old, new)
code = re.sub(r'\.testTag\("[^\"]*"\)', '', code)
code = code.replace('$', "${'$'}")
generated = (
    '// Generated by scripts/generate_marker_action_code.py.\n'
    'package com.toutiaoyan.compose.ui.catalog.docs\n\n'
    'internal val markerActionCode =\n    """\n'
    + '\n'.join('    ' + line if line else '' for line in code.splitlines())
    + '\n    """.trimIndent()\n'
)
(DOCS / 'MarkerActionCode.kt').write_text(generated)
