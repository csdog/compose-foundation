#!/usr/bin/env python3
"""Generate complete Radio Group snippets from the compiled catalog previews."""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'app/shared/src/commonMain/kotlin/com/toutiaoyan/compose/ui/catalog/docs'
source = (DOCS / 'RadioGroupDoc.kt').read_text()
EXAMPLES = {
    'Default': 'RadioGroupDemoPreview',
    'Description': 'RadioGroupDescriptionPreview',
    'ChoiceCard': 'RadioGroupChoiceCardPreview',
    'Fieldset': 'RadioGroupFieldsetPreview',
    'Disabled': 'RadioGroupDisabledPreview',
    'Invalid': 'RadioGroupInvalidPreview',
    'RTL': 'RadioGroupRtlContent',
    'Horizontal': 'RadioGroupHorizontalPreview',
    'Required': 'RadioGroupRequiredPreview',
}
DECLARATION = re.compile(
    r'^(?:@Composable\n)?private '
    r'(?:fun [^\n]*?\b(?P<function>\w+)\s*\(|(?:val|class) (?P<member>\w+)\b)',
    re.MULTILINE,
)


def main():
    definitions_source = source.split('\nval radioGroupDoc =', 1)[0]
    starts = list(DECLARATION.finditer(definitions_source))
    ends = [match.start() for match in starts[1:]] + [len(definitions_source)]
    definitions = {
        match['function'] or match['member']: definitions_source[match.start():end].strip()
        for match, end in zip(starts, ends)
    }
    imports = re.findall(r'^import [^\n]+', definitions_source, re.MULTILINE)
    output = [
        '// Generated by scripts/generate_radio_group_recipe_code.py from the compiled previews.',
        'package com.toutiaoyan.compose.ui.catalog.docs',
        '',
    ]
    for name, entry in EXAMPLES.items():
        selected = {entry}
        pending = [entry]
        while pending:
            body = definitions[pending.pop()]
            for dependency in definitions.keys() - selected:
                token = re.escape(dependency)
                declaration = definitions[dependency]
                reference = (
                    rf'\b{token}\s*\(|::\s*{token}\b'
                    if re.search(r'^private (?:fun|class) ', declaration, re.MULTILINE)
                    else rf'\b{token}\b'
                )
                if re.search(reference, body):
                    selected.add(dependency)
                    pending.append(dependency)
        body = '\n\n'.join(definitions[key] for key in definitions if key in selected)
        body = body.replace(f'private fun {entry}(', f'fun {entry}(', 1)
        used = [
            line for line in imports
            if re.search(rf'\b{re.escape(line.rsplit(".", 1)[1])}\b', body)
            or (line.rsplit('.', 1)[1] in ('getValue', 'setValue') and re.search(r'\bby\b', body))
        ]
        code = '\n\n'.join([
            '@file:OptIn(androidx.compose.foundation.style.ExperimentalFoundationStyleApi::class)',
            '\n'.join(used),
            body,
        ]).replace('$', "${'$'}")
        assert '"""' not in code
        output += [
            f'internal val radioGroup{name}RecipeCode =',
            '    """',
            *['    ' + line if line else '' for line in code.splitlines()],
            '    """.trimIndent()',
            '',
        ]
    target = DOCS / 'RadioGroupRecipeCode.kt'
    generated = '\n'.join(output)
    if not target.exists() or target.read_text() != generated:
        target.write_text(generated)
    print(f'Generated {len(EXAMPLES)} complete Radio Group snippets')


if __name__ == '__main__':
    main()
