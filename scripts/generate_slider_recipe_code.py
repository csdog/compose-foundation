#!/usr/bin/env python3
"""Generate standalone Slider snippets from the Kotlin recipes used by the catalog."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'app/shared/src/commonMain/kotlin/com/toutiaoyan/compose/ui/catalog/docs'
SOURCE = (DOCS / 'SliderRecipes.kt').read_text(encoding='utf-8')
HEADER = SOURCE.split('// region usage\n', 1)[0]
OPT_IN = next(line for line in HEADER.splitlines() if line.startswith('@file:'))
IMPORTS = [line for line in HEADER.splitlines() if line.startswith('import ')]
RECIPES = [
    'usage', 'default', 'range', 'multiple', 'vertical', 'controlled',
    'disabled', 'rtl', 'step', 'inverted', 'commit', 'minSteps',
]


def recipe_code(name):
    body = SOURCE.split(f'// region {name}\n', 1)[1].split(f'// endregion {name}', 1)[0].strip()
    imports = []
    for line in IMPORTS:
        symbol = line.rsplit('.', 1)[1]
        used = ' by ' in body if symbol in ('getValue', 'setValue') else re.search(rf'\b{symbol}\b', body)
        if used:
            imports.append(line)
    return '\n\n'.join([OPT_IN, '\n'.join(imports), body]).replace('$', "${'$'}")


output = [
    '// Generated by scripts/generate_slider_recipe_code.py. Edit SliderRecipes.kt.',
    'package com.toutiaoyan.compose.ui.catalog.docs',
    '',
    'internal const val sliderUsageImportCode =',
    f'    "{next(line for line in IMPORTS if line.endswith(".Slider"))}"',
    '',
]
for name in RECIPES:
    property_name = f'slider{name[0].upper()}{name[1:]}RecipeCode'
    output += [
        f'internal val {property_name} =',
        '    """',
        *['    ' + line if line else '' for line in recipe_code(name).splitlines()],
        '    """.trimIndent()',
        '',
    ]

target = DOCS / 'SliderRecipeCode.kt'
generated = '\n'.join(output)
if not target.exists() or target.read_text(encoding='utf-8') != generated:
    target.write_text(generated, encoding='utf-8')
print(f'Generated {len(RECIPES)} standalone Slider snippets')
