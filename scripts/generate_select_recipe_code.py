#!/usr/bin/env python3
"""Generate complete Select snippets from the compiled catalog previews."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'app/shared/src/commonMain/kotlin/com/toutiaoyan/compose/ui/catalog/docs'
SOURCES = ('SelectExtensionRecipes.kt', 'SelectPrimaryRecipes.kt', 'SelectFieldRecipes.kt')
EXAMPLES = {'Default': 'SelectDefaultPreview',
 'Align Item With Trigger': 'SelectAlignItemPreview',
 'Groups': 'SelectGroupsPreview',
 'Scrollable': 'SelectScrollablePreview',
 'Disabled': 'SelectDisabledPreview',
 'Invalid': 'SelectInvalidPreview',
 'RTL': 'SelectRtlContent',
 'Uncontrolled': 'SelectUncontrolledPreview',
 'Default open': 'SelectDefaultOpenPreview',
 'Compound': 'SelectCompoundPreview',
 'Default disabled': 'SelectDefaultDisabledPreview',
 'Small': 'SelectSmallPreview',
 'Default size': 'SelectDefaultSizePreview',
 'Scroll buttons': 'SelectScrollButtonsPreview',
 'Default invalid': 'SelectDefaultInvalidPreview',
 'Required': 'SelectRequiredPreview',
 'Default required': 'SelectDefaultRequiredPreview',
 'Default placeholder': 'SelectDefaultPlaceholderPreview',
 'Disabled select': 'SelectDisabledSelectPreview',
 'Non-modal': 'SelectNonModalPreview',
 'Modal': 'SelectModalPreview',
 'Default modal': 'SelectDefaultModalPreview',
 'Group heading': 'SelectGroupHeadingPreview',
 'Prevent item select': 'SelectPreventItemSelectPreview',
 'Custom text value': 'SelectCustomTextValuePreview',
 'Value': 'SelectValuePreview',
 'Separator': 'SelectSeparatorPreview',
 'Label': 'SelectLabelPreview',
 'Group': 'SelectGroupPreview',
 'Item': 'SelectItemPreview',
 'Accessible label': 'SelectAccessibleLabelPreview',
 'Default accessibility label': 'SelectDefaultAccessibilityLabelPreview',
 'Trigger': 'SelectTriggerPreview',
 'Content': 'SelectContentPreview',
 'Default content variant': 'SelectDefaultContentVariantPreview',
 'Default dismiss': 'SelectDefaultDismissPreview',
 'Side offset': 'SelectSideOffsetPreview',
 'Default side offset': 'SelectDefaultSideOffsetPreview',
 'Viewport': 'SelectViewportPreview',
 'Scroll up button': 'SelectScrollUpButtonPreview',
 'Scroll down button': 'SelectScrollDownButtonPreview'}
DECLARATION = re.compile(
    r'^(?:@Composable\n)?(?:internal|private) '
    r'(?:fun [^\n]*?\b(?P<function>\w+)\s*\(|(?:val|class) (?P<member>\w+)\b)',
    re.MULTILINE,
)


def snippets():
    definitions = {}
    imports = []
    for name in SOURCES:
        source = re.sub(r'^// recipe:[^\n]*\n', '', (DOCS / name).read_text(), flags=re.MULTILINE)
        imports += re.findall(r'^import [^\n]+', source, re.MULTILINE)
        starts = list(DECLARATION.finditer(source))
        ends = [match.start() for match in starts[1:]] + [len(source)]
        for match, end in zip(starts, ends):
            key = match['function'] or match['member']
            assert key not in definitions, key
            definitions[key] = source[match.start():end].strip()
    result = {}
    for title, entry in EXAMPLES.items():
        selected = {entry}
        pending = [entry]
        while pending:
            body = definitions[pending.pop()]
            for dependency in definitions.keys() - selected:
                if re.search(r'\b' + re.escape(dependency) + r'\b', body):
                    selected.add(dependency)
                    pending.append(dependency)
        body = '\n\n'.join(definitions[key] for key in definitions if key in selected)
        body = body.replace(f'internal fun {entry}(', f'fun {entry}(', 1)
        used = []
        for line in dict.fromkeys(imports):
            symbol = line.rsplit('.', 1)[1]
            if symbol == '*' or re.search(r'\b' + re.escape(symbol) + r'\b', body):
                used.append(line)
        result[title] = '\n\n'.join([
            '@file:OptIn(androidx.compose.foundation.style.ExperimentalFoundationStyleApi::class)',
            '\n'.join(used),
            body,
        ])
    return result


def main():
    output = [
        '// Generated by scripts/generate_select_recipe_code.py from compiled previews.',
        'package com.toutiaoyan.compose.ui.catalog.docs', '',
        'internal val selectRecipeCode =', '    mapOf(',
    ]
    for title, code in snippets().items():
        code = code.replace('$', "${'$'}")
        assert '\"\"\"' not in code
        output += [
            f'        "{title}" to', '            """',
            *['            ' + line if line else '' for line in code.splitlines()],
            '            """.trimIndent(),',
        ]
    output += ['    )', '']
    target = DOCS / 'SelectRecipeCode.kt'
    generated = '\n'.join(output)
    if not target.exists() or target.read_text() != generated:
        target.write_text(generated)
    print(f'Generated {len(EXAMPLES)} complete Select snippets')


if __name__ == '__main__':
    main()
